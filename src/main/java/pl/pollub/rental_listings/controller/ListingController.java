package pl.pollub.rental_listings.controller;

import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.*;
import org.springframework.web.server.ResponseStatusException;
import pl.pollub.rental_listings.model.Listing;
import pl.pollub.rental_listings.repository.ListingRepository;
import pl.pollub.rental_listings.security.CurrentUserService;

import java.util.List;

/**
 * REST API for managing apartment listings (CRUD).
 */
@RestController
@RequestMapping("/api/listings")
@RequiredArgsConstructor
public class ListingController {

    private final ListingRepository listingRepository;
    private final CurrentUserService currentUserService;

    // GET http://localhost:8080/api/listings?city=Lublin
    // GET http://localhost:8080/api/listings?ownerId=1
    @GetMapping
    public List<Listing> getListings(@RequestParam(required = false) String city,
                                     @RequestParam(required = false) Long ownerId) {
        if (ownerId != null) {
            return listingRepository.findByOwnerId(ownerId);
        }
        if (city != null && !city.isBlank()) {
            return listingRepository.findByCityIgnoreCase(city.trim());
        }
        return listingRepository.findAll();
    }

    @GetMapping("/{id}")
    public Listing getListingById(@PathVariable Long id) {
        return findListingOrThrow(id);
    }

    // POST http://localhost:8080/api/listings?ownerId=1
    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public Listing addListing(@Valid @RequestBody Listing listing) {
        listing.setId(null); // the id is always generated by the database
        listing.setOwner(currentUserService.getCurrentUser()); // the LANDLORD role is checked by SecurityConfig
        return listingRepository.save(listing);
    }

    @PutMapping("/{id}")
    public Listing updateListing(@PathVariable Long id, @Valid @RequestBody Listing updatedListing) {
        Listing existingListing = findListingOrThrow(id);
        currentUserService.checkIsOwner(existingListing);
        updatedListing.setId(id);
        updatedListing.setOwner(existingListing.getOwner()); // the owner cannot be changed
        return listingRepository.save(updatedListing);
    }

    @DeleteMapping("/{id}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void deleteListing(@PathVariable Long id) {
        Listing listing = findListingOrThrow(id);
        currentUserService.checkIsOwner(listing);
        listingRepository.delete(listing);
    }

    /** Returns the listing or responds with 404 Not Found if it does not exist. */
    private Listing findListingOrThrow(Long id) {
        return listingRepository.findById(id)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Listing not found: " + id));
    }
}