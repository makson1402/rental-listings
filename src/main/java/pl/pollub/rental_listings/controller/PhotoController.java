package pl.pollub.rental_listings.controller;

import jakarta.validation.Valid;
import lombok.RequiredArgsConstructor;
import org.springframework.http.HttpStatus;
import org.springframework.web.bind.annotation.DeleteMapping;
import org.springframework.web.bind.annotation.GetMapping;
import org.springframework.web.bind.annotation.PathVariable;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.ResponseStatus;
import org.springframework.web.bind.annotation.RestController;
import org.springframework.web.server.ResponseStatusException;
import pl.pollub.rental_listings.model.Listing;
import pl.pollub.rental_listings.model.Photo;
import pl.pollub.rental_listings.repository.ListingRepository;
import pl.pollub.rental_listings.repository.PhotoRepository;

import java.util.List;

/**
 * REST API for the photos of a single listing.
 * Photos are always accessed through their listing: /api/listings/{listingId}/photos
 */
@RestController
@RequestMapping("/api/listings/{listingId}/photos")
@RequiredArgsConstructor
public class PhotoController {

    private final PhotoRepository photoRepository;
    private final ListingRepository listingRepository;

    @GetMapping
    public List<Photo> getPhotos(@PathVariable Long listingId) {
        findListingOrThrow(listingId);
        return photoRepository.findByListingIdOrderByIdAsc(listingId);
    }

    @PostMapping
    @ResponseStatus(HttpStatus.CREATED)
    public Photo addPhoto(@PathVariable Long listingId, @Valid @RequestBody Photo photo) {
        photo.setId(null); // the id is always generated by the database
        photo.setListing(findListingOrThrow(listingId));
        return photoRepository.save(photo);
    }

    @DeleteMapping("/{photoId}")
    @ResponseStatus(HttpStatus.NO_CONTENT)
    public void deletePhoto(@PathVariable Long listingId, @PathVariable Long photoId) {
        Photo photo = photoRepository.findByIdAndListingId(photoId, listingId)
                .orElseThrow(() -> new ResponseStatusException(
                        HttpStatus.NOT_FOUND, "Photo " + photoId + " not found in listing " + listingId));
        photoRepository.delete(photo);
    }

    /** Returns the listing or responds with 404 Not Found if it does not exist. */
    private Listing findListingOrThrow(Long listingId) {
        return listingRepository.findById(listingId)
                .orElseThrow(() -> new ResponseStatusException(HttpStatus.NOT_FOUND, "Listing not found: " + listingId));
    }
}